// lib/period.ts 확인용 스크립트: node scripts/check-period.mjs
import assert from "node:assert/strict";
import { getPeriod } from "../lib/period.ts";

// 한국 시간 기준 시각을 쉽게 만들기 위해 +09:00 표기를 쓴다
const cases = [
  // [설명, 입력 시각, 기대하는 날짜 줄]  (공유 시각은 항상 월요일 오전 9시)
  ["월요일 오전 9시 전", "2026-10-12T08:30:00+09:00", "26.10.12. 월(10.6.-10.12. 오전)"],
  ["월요일 오전", "2026-10-12T09:30:00+09:00", "26.10.12. 월(10.6.-10.12. 오전)"],
  ["월요일 오후에 실행해도 기간 끝은 오전 9시", "2026-10-12T15:00:00+09:00", "26.10.12. 월(10.6.-10.12. 오전)"],
  ["월요일 자정 직후 00:05", "2026-10-12T00:05:00+09:00", "26.10.12. 월(10.6.-10.12. 오전)"],
  ["화요일에 실행하면 지난 월요일 기준", "2026-10-13T00:05:00+09:00", "26.10.12. 월(10.6.-10.12. 오전)"],
  ["목요일(오후)에 실행하면 지난 월요일 기준", "2026-10-15T15:00:00+09:00", "26.10.12. 월(10.6.-10.12. 오전)"],
  ["일요일 밤에 실행하면 그 전 월요일 기준", "2026-10-11T23:59:00+09:00", "26.10.5. 월(9.29.-10.5. 오전)"],
  ["다음 주 월요일", "2026-10-19T10:00:00+09:00", "26.10.19. 월(10.13.-10.19. 오전)"],
  ["달이 바뀌는 월요일", "2026-10-05T10:00:00+09:00", "26.10.5. 월(9.29.-10.5. 오전)"],
  ["해가 바뀌는 월요일", "2027-01-04T15:00:00+09:00", "27.1.4. 월(12.29.-1.4. 오전)"],
  ["UTC 입력도 한국 시간으로 계산 (UTC 일요일 15:30 = 한국 월요일 00:30)", "2026-10-11T15:30:00Z", "26.10.12. 월(10.6.-10.12. 오전)"],
];

let failed = 0;
for (const [name, input, expected] of cases) {
  const actual = getPeriod(new Date(input)).dateLine;
  const ok = actual === expected;
  if (!ok) failed += 1;
  console.log(`${ok ? "✅" : "❌"} ${name}\n   기대: ${expected}\n   결과: ${actual}`);
}

// 기간의 시작은 공유 월요일의 6일 전(화요일) 0시, 한국 시간
for (const input of ["2026-10-12T12:00:00+09:00", "2026-10-15T12:00:00+09:00"]) {
  assert.equal(getPeriod(new Date(input)).start.toISOString(), "2026-10-05T15:00:00.000Z"); // 10.6(화) 0시 KST
}
console.log("✅ 수집 기간은 직전 화요일 0시(한국 시간)에서 시작");

// 기간의 끝은 언제 실행하든 월요일 오전 9시(한국 시간 = UTC 0시)
for (const input of ["2026-10-12T08:30:00+09:00", "2026-10-12T15:00:00+09:00", "2026-10-15T15:00:00+09:00"]) {
  assert.equal(getPeriod(new Date(input)).end.toISOString(), "2026-10-12T00:00:00.000Z");
}
console.log("✅ 기간의 끝은 항상 월요일 오전 9시");

// 다음 주는 13일(화) 0시부터 시작한다 (10.12 오전 9시 이후~밤 12시 기사는 어느 주에도 들어가지 않음)
const week1 = getPeriod(new Date("2026-10-12T10:00:00+09:00"));
const week2 = getPeriod(new Date("2026-10-19T10:00:00+09:00"));
assert.equal(week2.start.toISOString(), "2026-10-12T15:00:00.000Z"); // 10.13(화) 0시 KST
assert.ok(week2.start.getTime() > week1.end.getTime());
console.log("✅ 다음 주 기간은 13일 0시부터 시작");

if (failed > 0) {
  console.log(`\n❌ ${failed}건 실패`);
  process.exit(1);
}
console.log("\n모두 통과했어요.");
